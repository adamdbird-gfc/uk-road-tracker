// Two distinct evidence channels: archived route versus genuinely matched OSM footway.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function matchedFootwayRoadEvidence('),end=page.indexOf('// Shadow experiment:',start);
assert(start>0&&end>start,'pedestrian reference evidence helper present');
const M=111320,D=Math.PI/180,p=(x,y=0)=>[x/M,y/M];
const xyz=(a,o)=>[(a[0]-o[0])*M*Math.cos(o[1]*D),(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1];if(d<.001)return 1e9;const t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const evaluate=new Function('xyz','proj',page.slice(start,end)+';return matchedFootwayRoadEvidence')(xyz,proj);
const network=[];
for(let i=0;i<8;i++)network.push({p:p(i*8),q:p((i+1)*8),kind:'secondary',group:'street',index:i});
for(let i=0;i<8;i++)network.push({p:p(i*8,5),q:p((i+1)*8,5),kind:'footway',group:'roadside-footway',index:i});
for(let i=0;i<8;i++)network.push({p:p(i*8,17),q:p((i+1)*8,17),kind:'footway',group:'separate-frontage',index:i});
network.push({p:p(32,-10),q:p(32,10),kind:'footway',group:'crossing',index:0});
const allRoads=new Set(Array.from({length:8},(_,i)=>i));
const footOnly=new Set(Array.from({length:8},(_,i)=>8+i));
const original=[...footOnly],roadsBefore=[...allRoads];
const verified=evaluate(footOnly,network,allRoads);
assert.equal(verified.footwayBacked.size,8,'mapped pedestrian footway independently verifies road proposal');
assert.equal(verified.rawOnly.size,0);
assert.equal(verified.matchedFootwayIntervals,8);
assert.equal(verified.support.get(0).footway,'roadside-footway');
assert(verified.support.get(0).lateral<6,'bounded footway-road offset reported');
const crossing=evaluate(new Set([24]),network,allRoads);
assert.equal(crossing.footwayBacked.size,0,'perpendicular pedestrian crossing must not justify entire road');
assert.equal(crossing.rawOnly.size,8,'archive-only proposals distinguished');
const frontage=evaluate(new Set(Array.from({length:8},(_,i)=>16+i)),network,allRoads);
assert.equal(frontage.footwayBacked.size,0,'separate distant frontage cannot infer adjacent road');
const empty=evaluate(new Set(),network,allRoads);
assert.equal(empty.matchedFootwayIntervals,0);
assert.equal(empty.footwayBacked.size,0);
assert.equal(empty.rawOnly.size,8);
assert.deepEqual([...allRoads],roadsBefore,'no physical credit modification');
assert.deepEqual([...footOnly],original,'no matched reference mutation');
assert(page.includes('matchedFootwayRoadEvidence(evidence,roads,pedestrianRoadPreview.additions)'),'runtime consumes actual selected footway intervals');
assert(page.includes("stroke(verified,'#36e3c2',4.8)"),'pedestrian-supported roads visually distinct');
assert(page.includes('previewOnly:true'),'experimental state is explicit');
console.log('PASS: matched footway confirms road proposals while crossing, frontage, raw-only and cumulative credits stay distinct');
