const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=html.indexOf('function selectIndependentRoadCorridors('),end=html.indexOf('// Read-only corridor correspondence',start);
assert(start>0&&end>start,'independent corridor selector exists');
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const select=new Function('metres',html.slice(start,end)+';return selectIndependentRoadCorridors')(metres);
const network=[],candidates=new Map(),held=new Map();
function addWay(group,kind,y,offset,footBase,omitted=false,n=5){
 const ids=[];
 for(let i=0;i<n;i++){const id=network.length;network.push({p:p(i*8,y),q:p((i+1)*8,y),group,index:i,kind});
  candidates.set(id,{roadId:id,osmWay:group,kind,footwayIds:[footBase+i],overlapMetres:8,bestOffsetMetres:offset,serviceRoad:kind==='service',outsideGpsCandidateList:omitted});
  ids.push(id);
 }return ids;
}
const publicIds=addWay('public-main-road','residential',0,5,0,true);
const pubIds=addWay('pub-access','service',4,5,0,false);
let result=select({candidates,held},network);
assert.deepEqual([...result.selected],publicIds,'public road outranks geometrically equivalent service road');
assert(!pubIds.some(id=>result.selected.has(id)),'pub service access not awarded merely because connected');
assert.equal(result.missingFromGps,5,'proposals independent of GPS shortlist');
assert(result.alternatives.some(x=>x.way==='pub-access'&&x.reason==='competing-corridor-stronger'),'loser explains competing evidence');
assert(result.previewOnly,'not coverage');
const other=addWay('station-path-road','residential',20,3,200,false);
result=select({candidates,held},network);
assert(other.every(id=>result.selected.has(id)),'independent route with different pedestrian evidence retained');
const isolated=addWay('short-entry','residential',10,2,500,false,2);
result=select({candidates,held},network);
assert(isolated.every(id=>!result.selected.has(id)),'short spur held without sustained support');
const equal=addWay('second-public-road','residential',7,5,0,false);
result=select({candidates,held},network);
assert(equal.every(id=>!result.selected.has(id)),'equal competing public-road alignment must remain ambiguous');
assert(publicIds.every(id=>!result.selected.has(id)),'original road also held on exact tie');
assert.equal(candidates.size,22,'audit input candidates unmodified');
assert(html.includes('selectIndependentRoadCorridors(independentRoadCandidates,roads)'),'runtime consumes independent OSM audit');
assert(html.includes('id="independentRoads" aria-pressed="false"'),'dedicated visual control');
assert(html.includes("stroke(lines,'#60a5fa',5)"),'independent blue overlay drawn separately');
assert(html.includes('independentRoadPreview:{selected:'),'Inspector reports selected/held provenance');
assert(html.includes('independentRoadPreview,experimentalCorrection,boundedCorridorRecovery,crossWayJunctionRecovery,roadsideConsolidation,corridorResolution,'),'canonical and previews remain separate');
console.log('PASS: independent public road, pub access rival, no GPS shortlist, distinct station, short spur, ambiguity, no credit');
