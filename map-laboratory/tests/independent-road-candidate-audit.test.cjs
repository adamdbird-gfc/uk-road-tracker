const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=html.indexOf('function auditRoadCorridorCandidates('),end=html.indexOf('// Read-only corridor correspondence',start);
assert(start>0&&end>start);
const M=111320,p=(x,y)=>[x/M,y/M];
const xyz=(a,o)=>[(a[0]-o[0])*M,(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1];const t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const audit=new Function('xyz','proj',html.slice(start,end)+';return auditRoadCorridorCandidates')(xyz,proj);
const network=[];
for(let i=0;i<4;i++)network.push({p:p(i*8,0),q:p((i+1)*8,0),kind:'footway',group:'pavement',index:i});
for(let i=0;i<4;i++)network.push({p:p(i*8,6),q:p((i+1)*8,6),kind:'residential',group:'public-road',index:i});
for(let i=0;i<4;i++)network.push({p:p(i*8,-7),q:p((i+1)*8,-7),kind:'service',group:'pub-access',index:i});
const selected=new Set([0,1,2,3]),gps=new Set();
let result=audit(selected,network,gps);
assert(result.candidates.size>0,'independent road candidates must be discovered with empty GPS shortlist');
assert(result.outsideGpsShortlist>0,'missed road candidates exposed');
assert([...result.candidates.values()].some(x=>x.osmWay==='public-road'));
assert([...result.candidates.values()].some(x=>x.serviceRoad),'service alternative remains explicitly inspectable, not silently assumed invalid');
assert(result.serviceRoadAlternatives>0,'service competitors are reported');
assert(result.previewOnly===true);
assert(gps.size===0&&selected.size===4,'no input set or canonical credit mutations');
const empty=audit(new Set(),network,gps);
assert.equal(empty.candidates.size,0,'no pedestrian evidence means no road proposals');
const distant=network.concat([{p:p(0,50),q:p(8,50),kind:'residential',group:'distant',index:0}]);
assert(![...audit(selected,distant,gps).candidates.values()].some(x=>x.osmWay==='distant'),'distant road excluded');
const cross=network.concat([{p:p(16,-12),q:p(16,12),kind:'residential',group:'crossing',index:0}]);
assert(![...audit(selected,cross,gps).candidates.values()].some(x=>x.osmWay==='crossing'),'perpendicular crossing not invented as parallel route');
const isolated=audit(new Set([0]),network,gps);
assert.equal(isolated.assessed,0,'single footway interval insufficient sustained evidence');
assert(html.includes('auditRoadCorridorCandidates(evidence,roads,candidateRefs)'),'runtime independent from GPS candidate shortlist');
assert(html.includes('independentRoadCandidateAudit:{'),'inspector contains per-reference candidate provenance');
assert(html.includes('independentRoadCandidates,')&&html.includes('roadFirstRouteEvidence,canonical,'),'existing credit return remains unchanged');
console.log('PASS: independent road discovery, GPS-shortlist omissions, rival service access, crossing and evidence holds');
