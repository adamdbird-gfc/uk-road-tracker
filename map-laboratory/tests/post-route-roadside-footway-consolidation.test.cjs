const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function consolidateExperimentalRoadsidePaths('),end=page.indexOf('// Read-only corridor correspondence',start);
assert(start>0&&end>start);
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const xyz=(a,o)=>[(a[0]-o[0])*M,(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const consolidate=new Function('xyz','metres','proj',page.slice(start,end)+';return consolidateExperimentalRoadsidePaths')(xyz,metres,proj);
const network=[];
for(let i=0;i<5;i++)network.push({p:p(i*8,0),q:p((i+1)*8,0),kind:'residential',group:'Clive Road',index:i});
for(let i=0;i<5;i++)network.push({p:p(i*8,5),q:p((i+1)*8,5),kind:'footway',group:'Clive Road pavement',index:i});
network.push({p:p(40,5),q:p(48,13),kind:'footway',group:'station entrance',index:0});
network.push({p:p(0,21),q:p(40,21),kind:'path',group:'park path',index:0});
const base={ids:new Set(network.map((_,i)=>i)),sources:new Map(network.map((_,i)=>[i,i<5?'experimental-road':'independent-path'])),independentPaths:new Set([5,6,7,8,9,10,11]),suppressedParallelPaths:new Set()};
const r=consolidate(base,network);
console.log('Consolidation debug:',r.reason,[...r.ambiguous],r.suppressed.size);
assert.deepEqual([...r.suppressed],[5,6,7,8,9],'continuous parallel pavement consolidated');
assert([0,1,2,3,4,10,11].every(id=>r.canonical.ids.has(id)),'road, station and independent park path retained');
assert(r.canonical.sources.get(5)===undefined,'suppressed path no longer credited');
assert(base.ids.has(5)&&base.sources.has(5),'original canonical input remains unchanged');
assert(!r.canonical.independentPaths.has(5),'retained path index reconciled with final coverage');
let off=consolidate({...base,ids:new Set([5,6,7,8,9,10,11])},network);
assert.equal(off.suppressed.size,0,'footpath cannot disappear without a credited road');
const shortIds=new Set([0,1,2,3,4,5,6,10,11]);
off=consolidate({...base,ids:shortIds},network);
assert.equal(off.suppressed.size,0,'short roadside path never suppressed in isolation');
const dual=network.concat(Array.from({length:5},(_,i)=>({p:p(i*8,10),q:p((i+1)*8,10),kind:'residential',group:'parallel second road',index:i})));
off=consolidate({...base,ids:new Set([...base.ids,...Array.from({length:5},(_,i)=>i+network.length)])},dual);
assert.equal(off.suppressed.size,0,'equidistant competing physical roads remain ambiguous');
const nearbyService=network.map(x=>({...x}));for(let i=0;i<5;i++)nearbyService[i].kind='service';
off=consolidate(base,nearbyService);
assert.equal(off.suppressed.size,0,'service road alone cannot erase roadside pedestrian evidence');
assert(page.includes('experimentalCorrection.enabled?consolidateExperimentalRoadsidePaths('),'operation gated to experimental mode only');
assert(page.includes('const canonical=roadsideConsolidation.canonical'),'final canonical output uses reconciled coverage');
assert(page.includes('roadsideConsolidation:{suppressed:'),'Inspector explains suppression');
console.log('PASS: redundant pavement removed, roads/station/park kept, absent road, short, ambiguous and service protected');
