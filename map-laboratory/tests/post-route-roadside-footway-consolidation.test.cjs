const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function consolidateExperimentalRoadsidePaths('),end=page.indexOf('// Read-only corridor correspondence',start);
assert(start>0&&end>start);
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const xyz=(a,o)=>[(a[0]-o[0])*M,(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const consolidate=new Function('xyz','metres','proj',page.slice(start,end)+';return consolidateExperimentalRoadsidePaths')(xyz,metres,proj);
const network=[];
for(let i=0;i<5;i++)network.push({p:p(i*8,0),q:p((i+1)*8,0),kind:'residential',group:'Clive Road',index:i});
for(let i=0;i<5;i++)network.push({p:p(i*8,5),q:p((i+1)*8,5),kind:'footway',group:'Clive Road pavement',index:i});
network.push({p:p(40,5),q:p(48,13),kind:'footway',group:'station entrance',index:0});
network.push({p:p(0,21),q:p(40,21),kind:'path',group:'park path',index:0});
const base={ids:new Set(network.map((_,i)=>i)),sources:new Map(network.map((_,i)=>[i,i<5?'experimental-road':'independent-path'])),independentPaths:new Set([5,6,7,8,9,10,11]),suppressedParallelPaths:new Set()};
const r=consolidate(base,network);
assert.deepEqual([...r.suppressed],[5,6,7,8,9],'continuous parallel pavement consolidated');
assert([0,1,2,3,4,10,11].every(id=>r.canonical.ids.has(id)),'road, station and independent park path retained');
assert(r.canonical.sources.get(5)===undefined,'suppressed path no longer credited');
assert(base.ids.has(5)&&base.sources.has(5),'original canonical input remains unchanged');
assert(!r.canonical.independentPaths.has(5),'retained path index reconciled with final coverage');
let off=consolidate({...base,ids:new Set([5,6,7,8,9,10,11])},network);
assert.equal(off.suppressed.size,0,'footpath cannot disappear without a credited road');
const shortIds=new Set([0,1,2,3,4,5,6,10,11]);
off=consolidate({...base,ids:shortIds},network);
assert.equal(off.suppressed.size,0,'short roadside path never suppressed in isolation');
const dual=network.concat(Array.from({length:5},(_,i)=>({p:p(i*8,10),q:p((i+1)*8,10),kind:'residential',group:'parallel second road',index:i})));
off=consolidate({...base,ids:new Set([...base.ids,...Array.from({length:5},(_,i)=>i+network.length)])},dual);
assert.equal(off.suppressed.size,0,'equidistant competing physical roads remain ambiguous');
const nearbyService=network.map(x=>({...x}));for(let i=0;i<5;i++)nearbyService[i].kind='service';
off=consolidate(base,nearbyService);
assert.equal(off.suppressed.size,0,'service road alone cannot erase roadside pedestrian evidence');
const dedicatedCycleway=network.concat(Array.from({length:5},(_,i)=>({p:p(i*8,5),q:p((i+1)*8,5),kind:'cycleway',group:'dedicated route',index:i})));
const cycleIds=Array.from({length:5},(_,i)=>network.length+i);
off=consolidate({...base,ids:new Set([...base.ids,...cycleIds])},dedicatedCycleway);
assert(cycleIds.every(id=>off.canonical.ids.has(id)),'parallel dedicated cycleway is retained as its own infrastructure');
const parkPath=network.concat(Array.from({length:5},(_,i)=>({p:p(i*8,6),q:p((i+1)*8,6),kind:'path',group:'separate greenway',index:i})));
const parkIds=Array.from({length:5},(_,i)=>network.length+i);
off=consolidate({...base,ids:new Set([...base.ids,...parkIds])},parkPath);
assert(parkIds.every(id=>off.canonical.ids.has(id)),'parallel independent path is retained');
// A complete, separately mapped *short pavement way* should not survive
// merely because the old rule required 3 intervals and 18 metres.
const shortComplete=network.concat([{p:p(8,5),q:p(20,5),kind:'footway',group:'single roadside pavement',index:0}]);
const singleId=network.length;
off=consolidate({...base,ids:new Set([...base.ids,singleId])},shortComplete);
assert(off.suppressed.has(singleId),'a complete, strongly aligned 12m pavement fragment is redundant when matching road already credited');
assert(!off.canonical.ids.has(singleId),'suppressed fragment disappears from canonical coverage');
assert(!off.canonical.independentPaths.has(singleId),'no orphan independent-path attribution remains');
const twoComplete=network.concat([
 {p:p(8,5),q:p(16,5),kind:'footway',group:'two-piece pavement',index:0},
 {p:p(16,5),q:p(24,5),kind:'footway',group:'two-piece pavement',index:1}
]);
off=consolidate({...base,ids:new Set([...base.ids,network.length,network.length+1])},twoComplete);
assert(off.suppressed.has(network.length)&&off.suppressed.has(network.length+1),'complete 16m parallel pavement run is reconciled');
const unfinished=twoComplete.concat([{p:p(24,5),q:p(40,5),kind:'footway',group:'two-piece pavement',index:2}]);
off=consolidate({...base,ids:new Set([...base.ids,network.length,network.length+1])},unfinished);
assert(!off.suppressed.has(network.length)&&!off.suppressed.has(network.length+1),'do not erase partial coverage of a longer independent OSM footway');
const badOffset=network.concat([{p:p(8,9),q:p(20,9),kind:'footway',group:'too-far pavement',index:0}]);
off=consolidate({...base,ids:new Set([...base.ids,network.length])},badOffset);
assert(!off.suppressed.has(network.length),'short way demands strong lateral correspondence');
const diagonal=network.concat([{p:p(8,5),q:p(20,16),kind:'footway',group:'station crossing',index:0}]);
off=consolidate({...base,ids:new Set([...base.ids,network.length])},diagonal);
assert(!off.suppressed.has(network.length),'station crossing cannot be interpreted as parallel road');
const noShortRoad=shortComplete.map(x=>({...x}));for(let i=0;i<5;i++)noShortRoad[i].kind='service';
off=consolidate({...base,ids:new Set([...base.ids,singleId])},noShortRoad);
assert(!off.suppressed.has(singleId),'short pavement not suppressed beside non-public service-road geometry');
assert(page.includes('experimentalCorrection.enabled?consolidateExperimentalRoadsidePaths('),'operation gated to experimental mode only');
assert(page.includes('const networkGlue=experimentalCorrection.enabled?recoverSourceBackedNetworkConnections(roadsideConsolidation.canonical,roads,prepared.lines)')&&page.includes('const canonical=networkGlue.canonical'),'final canonical output uses reconciled coverage');
assert(page.includes('roadsideConsolidation:{suppressed:'),'Inspector explains suppression');
console.log('PASS: redundant pavement removed, roads/station/park kept, absent road, short, ambiguous and service protected');
