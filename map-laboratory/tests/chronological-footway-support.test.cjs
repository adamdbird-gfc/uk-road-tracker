const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function chronologicalFootwaySupport('),end=page.indexOf('// Shadow experiment:',start);
assert(start>=0&&end>start);
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const evaluate=new Function('metres',page.slice(start,end)+';return chronologicalFootwaySupport')(metres);
const network=Array.from({length:5},(_,i)=>({p:p(i*8,5),q:p((i+1)*8,5),kind:'footway',group:'path',index:i}));
const resolution={runs:[{eligible:true,roadIds:[10,11,12],footIds:[0,1,2,3,4]}],ambiguous:new Set()};
const a=evaluate([[0,0,1,1,2,2,3,4]],network,resolution);
assert.deepEqual([...a.supported],[10,11,12],'ordered contiguous matched reference supports corridor');
assert.equal(a.orderedChains,1);
const interrupted=evaluate([[0,1,null,2,3]],network,resolution);
assert.equal(interrupted.supported.size,0,'unmatched probe breaks chronology');
assert.equal(interrupted.held.size,3);
const disconnected=evaluate([[0,2,4]],network,resolution);
assert.equal(disconnected.supported.size,0,'non-touching intervals are not chronological continuity');
const ambiguous=evaluate([[0,1,2,3]],network,{...resolution,ambiguous:new Set([11])});
assert.equal(ambiguous.supported.size,0,'competing road remains unresolved');
const cloned=[...resolution.runs[0].roadIds];
assert.deepEqual(resolution.runs[0].roadIds,cloned,'diagnostics do not mutate reference IDs');
assert(page.includes('selectedFootwaySequences.push(selectedFootwaySequence)'),'records actual matching sequence');
assert(page.includes('chronologicalFootwaySupport(selectedFootwaySequences,roads,corridorResolution)'),'runtime consumes time-ordered reference selection');
assert(page.includes('independentRoadCandidates,independentRoadPreview,experimentalCorrection,boundedCorridorRecovery,crossWayJunctionRecovery,corridorResolution,orderedCorridorSupport,connectedRouteEvidence,roadFirstRouteEvidence,canonical'),'diagnostics only in match response');
console.log('PASS: source probe order, gaps, discontinuity, ambiguity and non-crediting diagnostics');
