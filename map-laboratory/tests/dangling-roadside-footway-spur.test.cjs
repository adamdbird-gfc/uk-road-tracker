const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function suppressDanglingPedestrianSpurs('),end=page.indexOf('// Optional local single-journey Android match evidence.',start);
assert(start>0&&end>start,'output-only dangling spur suppression exists');
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const xyz=(a,o)=>[(a[0]-o[0])*M,(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const clean=new Function('metres','xyz','proj',page.slice(start,end)+';return suppressDanglingPedestrianSpurs')(metres,xyz,proj);
const road=Array.from({length:8},(_,i)=>({p:p(i*8,0),q:p((i+1)*8,0),kind:'residential',group:'through',index:i}));
const spur={p:p(24,0),q:p(24,12),kind:'footway',group:'pub spur',index:0};
const entrance={p:p(64,0),q:p(70,15),kind:'footway',group:'station entrance',index:0};
const net=[...road,spur,entrance];
const base={ids:new Set(net.map((_,i)=>i)),sources:new Map(net.map((_,i)=>[i,'original-match'])),independentPaths:new Set([8,9]),suppressedParallelPaths:new Set()};
const journey=[[p(0,0),p(64,0)]];
let result=clean(base,net,journey);
assert(result.suppressed.has(8),'tiny dead-end pedestrian spur at credited through-road removed');
assert(!result.suppressed.has(9),'station entrance at road endpoint remains');
assert([...Array(8).keys()].every(id=>result.canonical.ids.has(id)),'through-road is not shortened or changed');
assert(base.ids.has(8)&&base.sources.has(8),'original input, evidence and edits preserved');
assert(!result.canonical.sources.has(8)&&!result.canonical.independentPaths.has(8),'no orphan credited path');
result=clean({...base,ids:new Set([8,9])},net,journey);
assert.equal(result.suppressed.size,0,'do not erase pedestrian paths without credited road');
result=clean(base,net.concat([{p:p(24,12),q:p(24,36),kind:'footway',group:'connecting footway',index:0}]),journey);
assert(!result.suppressed.has(8),'genuine independent pedestrian connection retained');
result=clean(base,net,[[p(0,0),p(24,12)]]);
assert(!result.suppressed.has(8),'journey ending at the footpath tip must not be erased');
const long=net.map(x=>({...x}));long[8]={...spur,q:p(24,27)};
result=clean(base,long,journey);
assert(!result.suppressed.has(8),'longer independent pedestrian branch retained');
const walkOnly=net.map(x=>({...x}));for(let i=0;i<8;i++)walkOnly[i].kind='service';
result=clean(base,walkOnly,journey);
assert(!result.suppressed.has(8),'service roads cannot justify pedestrian suppression');
