const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const begin=page.indexOf('function recoverCanonicalRoadCorridors('),end=page.indexOf('// Read-only corridor correspondence',begin);
assert(begin>=0&&end>begin);
const M=111320,p=(x,y=0)=>[x/M,y/M],metres=(a,b)=>Math.hypot((a[0]-b[0])*M,(a[1]-b[1])*M);
const xyz=(a,o)=>[(a[0]-o[0])*M,(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const apply=new Function('xyz','metres','proj',page.slice(begin,end)+';return recoverCanonicalRoadCorridors')(xyz,metres,proj);
const network=Array.from({length:6},(_,i)=>({p:p(i*8,0),q:p((i+1)*8,0),index:i,kind:'residential'}));
network.push({p:p(48,-8),q:p(48,-16),kind:'footway'}); // independent station entrance
const baseline={ids:new Set([0,1,6]),sources:new Map([[0,'direct'],[1,'direct'],[6,'independent-path']]),independentPaths:new Set([6])};
const run={ids:[0,1,2,3,4,5],kind:'residential',length:48,footIds:[10,11,12,13,14,15]};
const preview={runs:[run]};
const gps=[[p(0,6),p(48,6)]];
let result=apply(baseline,preview,network,gps);
assert.deepEqual([...result.added],[2,3,4,5],'corrected credit adds missing physical road intervals');
assert.deepEqual([...baseline.ids],[0,1,6],'baseline credits are unchanged');
assert(result.canonical.ids.has(6),'genuine station entrance preserved');
assert(result.canonical.sources.get(2)==='experimental-supported-road-corridor');
assert.equal(result.correctedCount,result.baselineCount+4);
const bad=apply(baseline,preview,network,[[p(0,40),p(48,40)]]);
assert.equal(bad.added.size,0,'unsupported distant route cannot be credited');
const crossing=apply(baseline,preview,network,[[p(24,-10),p(24,10)]]);
assert.equal(crossing.added.size,0,'perpendicular pedestrian crossing does not credit entire road');
const service=apply(baseline,{runs:[{...run,kind:'service'}]},network,gps);
assert.equal(service.added.size,0,'pub-side service access never auto-credited');
const stub=apply(baseline,{runs:[{...run,ids:[2,3],length:16}]},network,gps);
assert.equal(stub.added.size,0,'short unsupported route not forced into coverage');
const parallelWrong=apply(baseline,{runs:[run]},network,[[p(0,6),p(16,6)]]);
assert.equal(parallelWrong.added.size,0,'partial source segment cannot credit unsupported long run');
assert(page.includes('experimentalRecovery&&j[2]'),'correction gated to walking');
assert(page.includes('const canonical=crossWayJunctionRecovery.canonical'),'correction and bounded bridge enter canonical coverage pipeline');
assert(page.includes('return {ids:canonical.ids,'),'renderer consumes corrected canonical identifiers');
assert(page.includes('resetAttribution();step=0;'),'A/B invalidates historical credit');
assert(page.includes('<details id="advanced">'),'clutter tucked behind advanced disclosure');
assert(page.includes('id="experimentalCoverage" aria-pressed="false"'),'baseline default preserved');
assert(!page.includes('experimentalRecovery=true'),'correction cannot start enabled');
console.log('PASS: actual canonical recovery, baseline immutability, pedestrian entrance, distant/short/crossing/service holds, UI A/B');
