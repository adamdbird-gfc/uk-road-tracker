// Stage-by-stage provenance uses synthetic road IDs only.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const a=html.indexOf('function tracePhysicalCoverageStages('),b=html.indexOf('// Display-only micro-links',a);
assert(a>=0&&b>a,'coverage provenance function available');
const trace=new Function(html.slice(a,b)+';return tracePhysicalCoverageStages')();
const roads=Array.from({length:9},(_,id)=>({kind:id===3||id===6?'footway':'residential'}));
const direct=new Set([0,1,2,3,4,5,6]);
const retained=new Set([0,1,2,3,4,6]);
const base={ids:new Set([0,2,4,7]),roadPromotions:{promoted:new Set([7])},suppressedParallelPaths:new Set([3,6])};
const final={ids:new Set([0,2,4,7,8])};
const gapRepair={added:new Set([8])};
const got=trace(direct,retained,base,final,gapRepair,roads);
assert.equal(got.selected,7);
assert.equal(got.selectedCredited,3);
assert.equal(got.directNotCredited,4);
assert.equal(got.classified['parallel-pavement-consolidated'],2);
assert.equal(got.classified['confidence-rule-held'],1);
assert.equal(got.classified['selected-but-not-credited'],1);
assert.equal(got.stageOf(0),'selected-and-credited');
assert.equal(got.stageOf(3),'parallel-pavement-consolidated');
assert.equal(got.stageOf(5),'confidence-rule-held');
assert.equal(got.stageOf(1),'selected-but-not-credited');
assert.equal(got.stageOf(7),'promoted-road-centreline');
assert.equal(got.stageOf(8),'source-backed-road-gap');
assert.equal(got.stageOf(20),'not-selected');
assert.equal(got.promoted,1);
assert.equal(got.recovered,1);
assert.equal(got.finalRoad,5);
assert.equal(got.finalPaths,0);
assert.deepEqual([...direct],[0,1,2,3,4,5,6],'input evidence untouched');
assert.deepEqual([...final.ids],[0,2,4,7,8],'credited network untouched');
assert(html.includes("coverageStage:m?.coverageTrace?.stageOf(best)"),'inspector reports selected reference stage');
assert(html.includes("r.first===Infinity?'never'"),'uncredited reference is inspectable');
console.log('PASS: credited, consolidated, withheld and unselected reference provenance without coverage changes');
