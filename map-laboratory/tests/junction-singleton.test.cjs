// Synthetic junction-only evidence; no user coordinates or archive.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const start=page.indexOf('function excludedJunctionSingletons(');
const end=page.indexOf('const unsupportedJunction=excludedJunctionSingletons(',start);
assert.ok(start>0&&end>start,'pure junction evidence classifier present');
const M=111320,D=Math.PI/180;
const xyz=(a,o)=>[(a[0]-o[0])*M*Math.cos(o[1]*D),(a[1]-o[1])*M];
const proj=(a,b,p)=>{const v=[b[0]-a[0],b[1]-a[1]],d=v[0]*v[0]+v[1]*v[1];if(d<.001)return 1e9;const t=Math.max(0,Math.min(1,((p[0]-a[0])*v[0]+(p[1]-a[1])*v[1])/d));return Math.hypot(p[0]-a[0]-t*v[0],p[1]-a[1]-t*v[1])};
const classify=new Function('xyz','proj',page.slice(start,end)+';return excludedJunctionSingletons')(xyz,proj);
const pt=(x,y=0)=>[x/M,y/M],roads=[];
for(let i=0;i<5;i++)roads.push({group:'through',index:i,kind:'residential',p:pt(i*8),q:pt((i+1)*8)});
for(let i=0;i<4;i++)roads.push({group:'branch',index:i,kind:'tertiary',p:pt(18,i*8),q:pt(18,(i+1)*8)});
const groups=new Map([['through',[0,1,2,3,4]],['branch',[5,6,7,8]]]);
const evidence=new Set([0,1,2,3,4,5]),hits=new Map();
for(let i=0;i<5;i++)hits.set(i,[{sourceSegment:9,sourcePoint:pt(18),selectionScore:1}]);
hits.set(5,[{sourceSegment:9,sourcePoint:pt(18),selectionScore:.4}]);
assert.ok(classify(roads,groups,evidence,hits).has(5),'single competing terminal branch held');
roads[5].kind='footway';
assert.ok(!classify(roads,groups,evidence,hits).has(5),'single short connecting footway kept');
roads[5].kind='tertiary';
hits.get(5).push({sourceSegment:10,sourcePoint:pt(18,5),selectionScore:2});
assert.ok(!classify(roads,groups,evidence,hits).has(5),'repeated evidence keeps short road');
hits.get(5).pop();
for(let i=0;i<5;i++)hits.get(i)[0].sourceSegment=18;
assert.ok(!classify(roads,groups,evidence,hits).has(5),'unrelated source leg cannot suppress branch');
for(let i=0;i<5;i++)hits.get(i)[0].sourceSegment=9;
for(let i=0;i<5;i++)roads[i].p=pt(100+i*8),roads[i].q=pt(108+i*8);
assert.ok(!classify(roads,groups,evidence,hits).has(5),'far-away road cannot suppress branch');
console.log('PASS: isolated false branch held; valid footway, repeated branch, distinct leg and distant road preserved');
