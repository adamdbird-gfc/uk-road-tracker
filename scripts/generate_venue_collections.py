#!/usr/bin/env python3
"""Compile reviewed collection data into the offline registry; --check detects drift."""
import argparse,json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE=ROOT/'collections/venue-collections-v1.json'
OUTPUT=ROOT/'android-prototype/app/src/main/java/com/roadprints/capture/VenueCollectionConfig.java'
def generate(data):
    if data.get('schema_version')!=1:raise ValueError('Unsupported registry')
    ids=set();goals=set()
    for c in data['collections']:
        if not re.fullmatch('[a-z][a-z0-9-]*',c['id']) or c['id'] in ids:raise ValueError('Duplicate collection')
        ids.add(c['id'])
        if c['catalogue_format'] not in ('services_v1','reviewed_map_v1') or not 0<c['radius']<=125:raise ValueError('Unreviewed policy')
        if '..' in c['catalogue_asset'] or c['catalogue_asset'].startswith('/'):raise ValueError('Invalid asset')
        for g in c['achievements']:
            if g['id'] in goals or g['measure'] not in ('any','count','percent','groups','distinct_history') or g['target']<=0:raise ValueError('Invalid goal')
            goals.add(g['id'])
            if 'levels' in g and (g['levels']!=sorted(set(g['levels'])) or len(g['levels'])!=len(g['level_titles'])):raise ValueError('Invalid levels')
    payload=json.dumps(data,ensure_ascii=False,separators=(',',':'))
    chunks=[json.dumps(payload[i:i+6000],ensure_ascii=False) for i in range(0,len(payload),6000)]
    return '// Generated by scripts/generate_venue_collections.py. Edit collections/venue-collections-v1.json.\npackage com.roadprints.capture;\nfinal class VenueCollectionConfig {\n    static org.json.JSONObject read(){try{return new org.json.JSONObject(\n        '+ '\n        + '.join(chunks)+');}catch(org.json.JSONException invalid){throw new IllegalStateException("Invalid compiled collection registry",invalid);}}\n    private VenueCollectionConfig(){}\n}\n'
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    rendered=generate(json.loads(SOURCE.read_text()))
    if a.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=rendered:raise SystemExit('Registry is stale: run python3 scripts/generate_venue_collections.py')
    else:OUTPUT.write_text(rendered)
if __name__=='__main__':main()
